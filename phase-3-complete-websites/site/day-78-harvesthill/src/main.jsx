import React from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter, HashRouter } from 'react-router-dom';
import App from './App.jsx';
import { assetPath } from './assetPath';
import './styles/global.css';
document.documentElement.style.setProperty('--hero-image', `url(${assetPath('images/hero-fields.jpg')})`);
const Router = location.protocol === 'file:' ? HashRouter : BrowserRouter;
const routerProps = location.protocol === 'file:' ? {} : { basename: import.meta.env.BASE_URL };
createRoot(document.getElementById('root')).render(<React.StrictMode><Router {...routerProps}><App/></Router></React.StrictMode>);
